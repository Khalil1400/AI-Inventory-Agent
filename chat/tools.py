from .models import Item
from decimal import Decimal, InvalidOperation, ROUND_HALF_UP


def calculate_cost(name, quantity, vat_percent=0):
    """Find the total price including VAT."""
    from .local_commands import find_item
    item = find_item(name)
    if item is None:
        return {"error": f"No item named '{name}' exists in the inventory."}
    if isinstance(quantity, bool) or not isinstance(quantity, int) or quantity <= 0:
        return {"error": "Quantity must be a positive whole number."}
    try:
        vat_rate = Decimal(str(vat_percent))
    except (InvalidOperation, ValueError):
        return {"error": "VAT must be a non-negative number."}
    if not vat_rate.is_finite() or vat_rate < 0:
        return {"error": "VAT must be a non-negative number."}
    if item.price <= 0:
        return {"error": f"Set a price for {item.name} first."}
    # First calculate the price, then add VAT.
    subtotal = item.price * quantity
    vat = subtotal * vat_rate / 100
    vat = vat.quantize(Decimal('0.01'), rounding=ROUND_HALF_UP)
    total = subtotal + vat
    return {"name": item.name, "quantity": quantity, "unit_price": str(item.price),
            "subtotal": str(subtotal), "vat_percent": str(vat_rate),
            "vat": str(vat), "total": str(total)}


def check_stock(name):
    """Look up how many of an item we have."""
    item = Item.objects.filter(name__iexact=name).first()
    if item is None:
        return {"error": f"No item named '{name}' exists in the inventory."}
    return {"name": item.name, "quantity": item.quantity}


def list_items():
    """Return every item in the inventory."""
    items = Item.objects.all()
    return {"items": [{"name": i.name, "quantity": i.quantity} for i in items]}


def add_item(name, quantity):
    """Create a new item, or add to an existing one's stock."""
    item = Item.objects.filter(name__iexact=name).first()
    if item is not None:
        item.quantity += quantity
        item.save()
        return {"name": item.name, "quantity": item.quantity, "created": False}
    item = Item.objects.create(name=name, quantity=quantity)
    return {"name": item.name, "quantity": item.quantity, "created": True}


def remove_stock(name, quantity):
    """Take a quantity out of stock."""
    item = Item.objects.filter(name__iexact=name).first()
    if item is None:
        return {"error": f"No item named '{name}' exists in the inventory."}
    if quantity > item.quantity:
        return {
            "error": f"Cannot remove {quantity}. Only {item.quantity} in stock.",
            "name": item.name,
            "quantity": item.quantity,
        }
    item.quantity -= quantity
    item.save()
    return {"name": item.name, "quantity": item.quantity}


def delete_item(name):
    """Remove an item from the inventory entirely."""
    item = Item.objects.filter(name__iexact=name).first()
    if item is None:
        return {"error": f"No item named '{name}' exists in the inventory."}
    item.delete()
    return {"deleted": name}


